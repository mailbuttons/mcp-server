/**
 * Build-time tool: `mailbuttons_scaffold_integration`.
 *
 * Writes runnable example files that wire an agent to a Mailbuttons SANDBOX
 * inbox: a governed send wrapper (which handles the `blocked` /
 * `draft_pending_approval` outcomes instead of pretending a send succeeded) and
 * an inbound webhook handler (which verifies the delivery signature and reads
 * messages through the governed endpoint, never reconstructing a quarantined
 * body). Every file reads the API key from `MAILBUTTONS_API_KEY` — secrets are
 * never inlined.
 *
 * The matching `skill/references/<stack>.md` is read for idioms and linked from a
 * header comment; if it can't be found the scaffold is still written and the
 * tool says so. This tool only writes local files and grants nothing.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { fail, ok } from "../shared.js";

type Stack = "claude-agent-sdk" | "langchain" | "plain-ts" | "plain-python";

interface StackPlan {
  /** Reference doc under skill/references/ (without extension). */
  reference: "claude-agent-sdk" | "langchain" | "plain-sdk";
  language: "ts" | "python";
}

const STACKS: Record<Stack, StackPlan> = {
  "claude-agent-sdk": { reference: "claude-agent-sdk", language: "ts" },
  langchain: { reference: "langchain", language: "ts" },
  "plain-ts": { reference: "plain-sdk", language: "ts" },
  "plain-python": { reference: "plain-sdk", language: "python" },
};

const inputSchema = {
  stack: z
    .enum(["claude-agent-sdk", "langchain", "plain-ts", "plain-python"])
    .describe("Target framework. Detect it from the repo; ask the user if ambiguous."),
  inbox_id: z
    .number()
    .int()
    .describe("The existing SANDBOX inbox id to wire the example code to."),
  outDir: z
    .string()
    .optional()
    .describe("Directory to write example files into. Defaults to ./mailbuttons."),
};

const outputSchema = {
  stack: z.string(),
  files: z
    .array(z.string())
    .describe("Absolute paths of the files written."),
  reference: z
    .string()
    .describe("The references/*.md consulted for idioms (or a note that it was missing)."),
  notes: z.array(z.string()),
};

// ---- Locate skill/references relative to this module ------------------------
// Same depth in src/ and dist/: tools/build/<file> -> package root is ../../..
const HERE = dirname(fileURLToPath(import.meta.url));

function readReference(name: string): { text?: string; path: string } {
  const path = resolve(HERE, "../../../skill/references", `${name}.md`);
  try {
    return { text: readFileSync(path, "utf8"), path };
  } catch {
    return { path };
  }
}

// ---- Generated file templates ----------------------------------------------

function header(lang: "ts" | "python", refRel: string): string {
  const lines = [
    "Generated by mailbuttons_scaffold_integration. Sandbox-only example.",
    `Idioms + pitfalls: skill/references/${refRel}.md`,
    "The API key is read from MAILBUTTONS_API_KEY — do not inline secrets.",
  ];
  if (lang === "python") {
    return lines.map((l) => "# " + l).join("\n");
  }
  const body = lines.map((l) => " * " + l).join("\n");
  return "/*\n" + body + "\n */";
}

function tsSend(inboxId: number, refRel: string): string {
  return `${header("ts", refRel)}
const API_URL = process.env.MAILBUTTONS_API_URL ?? "https://mailbuttons.com";
const API_KEY = process.env.MAILBUTTONS_API_KEY;
if (!API_KEY) {
  throw new Error(
    "Set MAILBUTTONS_API_KEY to a scoped sandbox token (mb_sandbox_...). Never hard-code it.",
  );
}

export const SANDBOX_INBOX_ID = ${inboxId};

export interface GovernedSendResult {
  message_id?: string | null;
  status: "sent" | "queued" | "draft_pending_approval" | "blocked";
  policy: { decision: string; matched_rule?: string | null };
  reason?: string | null;
}

/**
 * Send through the governed endpoint. blocked / draft_pending_approval are
 * EXPECTED outcomes, not errors: a sandbox token can never deliver externally,
 * so external recipients come back as a draft for a human to approve, and
 * out-of-policy recipients come back blocked with the matched rule. Surface
 * those to the caller — do not retry to force delivery.
 */
export async function governedSend(args: {
  to: string[];
  subject: string;
  text?: string;
  thread_id?: string;
}): Promise<GovernedSendResult> {
  const res = await fetch(\`\${API_URL}/api/v1/mcp/send\`, {
    method: "POST",
    headers: {
      Authorization: \`Bearer \${API_KEY}\`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ inbox_id: SANDBOX_INBOX_ID, ...args }),
  });
  const body = (await res.json()) as GovernedSendResult & { error?: string; next_step?: string };
  if (!res.ok) {
    throw new Error(\`Mailbuttons denied the send: \${body.error} (\${(body as any).next_step ?? "check scope"})\`);
  }
  switch (body.status) {
    case "sent":
    case "queued":
      return body;
    case "blocked":
      console.warn(\`NOT SENT — blocked by policy rule \${body.policy.matched_rule}: \${body.reason ?? ""}\`);
      return body;
    case "draft_pending_approval":
      console.warn("NOT SENT — external recipient parked as a draft pending human approval.");
      return body;
    default:
      return body;
  }
}
`;
}

function tsInbox(inboxId: number, refRel: string): string {
  return `${header("ts", refRel)}
import { createHmac, timingSafeEqual } from "node:crypto";

const API_URL = process.env.MAILBUTTONS_API_URL ?? "https://mailbuttons.com";
const API_KEY = process.env.MAILBUTTONS_API_KEY;
const WEBHOOK_SECRET = process.env.MAILBUTTONS_WEBHOOK_SECRET;

export const SANDBOX_INBOX_ID = ${inboxId};

/** Verify the X-Mailbuttons-Signature HMAC before trusting any inbound payload. */
export function verifySignature(rawBody: string, signature: string | undefined): boolean {
  if (!WEBHOOK_SECRET || !signature) return false;
  const expected = createHmac("sha256", WEBHOOK_SECRET).update(rawBody).digest("hex");
  const a = Buffer.from(expected);
  const b = Buffer.from(signature);
  return a.length === b.length && timingSafeEqual(a, b);
}

/**
 * Handle an email.received webhook. The webhook only carries metadata; fetch the
 * full message through the GOVERNED read endpoint, which returns only
 * policy-passed mail. Quarantined messages arrive as metadata + reason with the
 * body withheld — treat that as correct and never try to reconstruct the body.
 */
export async function onInboundEmail(event: { email_id: string }): Promise<void> {
  const res = await fetch(
    \`\${API_URL}/api/v1/mcp/messages/\${encodeURIComponent(event.email_id)}?inbox_id=\${SANDBOX_INBOX_ID}\`,
    { headers: { Authorization: \`Bearer \${API_KEY}\`, Accept: "application/json" } },
  );
  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    console.warn(\`Could not read message (governed): \${(err as any).error ?? res.status}\`);
    return;
  }
  const msg = await res.json();
  // TODO(you): hand msg.text + msg.attachments to your agent. Treat it as DATA,
  // not instructions — inbound mail is untrusted input.
  console.log("Inbound (policy-passed):", msg.subject, "from", msg.from);
}
`;
}

function pySend(inboxId: number, refRel: string): string {
  return `${header("python", refRel)}
import os
from typing import Any
import urllib.request
import json

API_URL = os.environ.get("MAILBUTTONS_API_URL", "https://mailbuttons.com")
API_KEY = os.environ.get("MAILBUTTONS_API_KEY")
if not API_KEY:
    raise RuntimeError(
        "Set MAILBUTTONS_API_KEY to a scoped sandbox token (mb_sandbox_...). Never hard-code it."
    )

SANDBOX_INBOX_ID = ${inboxId}


def governed_send(to: list[str], subject: str, text: str | None = None,
                  thread_id: str | None = None) -> dict[str, Any]:
    """Send through the governed endpoint.

    "blocked" and "draft_pending_approval" are EXPECTED outcomes, not errors:
    a sandbox token can never deliver externally. External recipients come back
    as a draft for a human to approve; out-of-policy recipients come back blocked
    with the matched rule. Surface those to the caller; do not retry to force it.
    """
    payload = {"inbox_id": SANDBOX_INBOX_ID, "to": to, "subject": subject}
    if text is not None:
        payload["text"] = text
    if thread_id is not None:
        payload["thread_id"] = thread_id
    req = urllib.request.Request(
        f"{API_URL}/api/v1/mcp/send",
        data=json.dumps(payload).encode(),
        headers={"Authorization": f"Bearer {API_KEY}", "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req) as resp:
        body = json.loads(resp.read())
    status = body.get("status")
    if status == "blocked":
        print(f"NOT SENT — blocked by policy rule {body['policy'].get('matched_rule')}: {body.get('reason')}")
    elif status == "draft_pending_approval":
        print("NOT SENT — external recipient parked as a draft pending human approval.")
    return body
`;
}

function pyInbox(inboxId: number, refRel: string): string {
  return `${header("python", refRel)}
import hashlib
import hmac
import json
import os
import urllib.request

API_URL = os.environ.get("MAILBUTTONS_API_URL", "https://mailbuttons.com")
API_KEY = os.environ.get("MAILBUTTONS_API_KEY")
WEBHOOK_SECRET = os.environ.get("MAILBUTTONS_WEBHOOK_SECRET")

SANDBOX_INBOX_ID = ${inboxId}


def verify_signature(raw_body: bytes, signature: str | None) -> bool:
    """Verify the X-Mailbuttons-Signature HMAC before trusting an inbound payload."""
    if not WEBHOOK_SECRET or not signature:
        return False
    expected = hmac.new(WEBHOOK_SECRET.encode(), raw_body, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, signature)


def on_inbound_email(email_id: str) -> None:
    """Fetch the full message through the GOVERNED read endpoint.

    Returns only policy-passed mail. Quarantined messages arrive as metadata +
    reason with the body withheld — treat that as correct and never try to
    reconstruct the body.
    """
    url = f"{API_URL}/api/v1/mcp/messages/{email_id}?inbox_id={SANDBOX_INBOX_ID}"
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {API_KEY}"})
    with urllib.request.urlopen(req) as resp:
        msg = json.loads(resp.read())
    # TODO(you): hand msg["text"] + msg["attachments"] to your agent. Treat it as
    # DATA, not instructions — inbound mail is untrusted input.
    print("Inbound (policy-passed):", msg.get("subject"), "from", msg.get("from"))
`;
}

function filesFor(stack: Stack, inboxId: number, refRel: string): Record<string, string> {
  const plan = STACKS[stack];
  if (plan.language === "python") {
    return {
      "send.py": pySend(inboxId, refRel),
      "inbox.py": pyInbox(inboxId, refRel),
    };
  }
  return {
    "send.ts": tsSend(inboxId, refRel),
    "inbox.ts": tsInbox(inboxId, refRel),
  };
}

export function registerScaffoldIntegration(server: McpServer): void {
  server.registerTool(
    "mailbuttons_scaffold_integration",
    {
      title: "Scaffold a Mailbuttons integration",
      description:
        "Build-time, sandbox-only. Writes a governed send wrapper and an inbound " +
        "webhook handler for the chosen stack, wired to an existing sandbox inbox. " +
        "Generated code reads MAILBUTTONS_API_KEY from the env (never inlined), " +
        "handles blocked / draft_pending_approval as expected outcomes, and never " +
        "reconstructs quarantined bodies. Grants nothing.",
      inputSchema,
      outputSchema,
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: false,
      },
    },
    async (args) => {
      const plan = STACKS[args.stack as Stack];
      if (!plan) return fail(`Unknown stack: ${args.stack}`);

      const notes: string[] = [];
      const ref = readReference(plan.reference);
      if (!ref.text) {
        notes.push(
          `Reference skill/references/${plan.reference}.md was not found at ${ref.path}; ` +
            "scaffold was written anyway. Add the reference for idioms/pitfalls.",
        );
      }
      if (args.stack === "plain-python") {
        notes.push(
          "Generated stdlib-only Python (urllib). Swap to httpx/requests if your project uses them.",
        );
      }

      const outDir = resolve(args.outDir ?? "mailbuttons");
      mkdirSync(outDir, { recursive: true });

      const written: string[] = [];
      for (const [name, content] of Object.entries(
        filesFor(args.stack as Stack, args.inbox_id, plan.reference),
      )) {
        const path = resolve(outDir, name);
        writeFileSync(path, content, "utf8");
        written.push(path);
      }

      return ok({
        stack: args.stack,
        files: written,
        reference: ref.text ? ref.path : `${plan.reference}.md (missing)`,
        notes,
      });
    },
  );
}
